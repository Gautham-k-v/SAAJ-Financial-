export const loanSeed = specs.map((spec) => assembleLoan(spec))

function paidThrough(count, amount) {
  const paid = {}
  for (let number = 1; number <= count; number += 1) paid[number] = amount
  return paid
}

function entry(at, action, detail) {
  return { id: `AUD-${at}-${action}`, at, action, detail }
}
